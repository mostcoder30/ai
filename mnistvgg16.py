# Step 1: Import libraries
import numpy as np
import tensorflow as tf
import matplotlib.pyplot as plt

from tensorflow.keras.datasets import fashion_mnist
from tensorflow.keras.utils import to_categorical
from tensorflow.keras.applications import vgg16
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Input, GlobalAveragePooling2D, Dense, Dropout
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau

# Step 2: Load Fashion-MNIST dataset
(X_train, y_train), (X_test, y_test) = fashion_mnist.load_data()

print(X_train.shape)
print(y_train.shape)
print(X_test.shape)
print(y_test.shape)

# Step 3: Display sample images
fig, axes = plt.subplots(2, 4, figsize=(10, 5))

for i, ax in enumerate(axes.flat):
    ax.imshow(X_train[i], cmap='gray')
    ax.set_title(y_train[i])
    ax.axis('off')

plt.tight_layout()
plt.show()

# Step 4: Select only Bag, Dress and Pullover
# Original labels: Pullover=2, Dress=3, Bag=8

train_mask = np.isin(y_train, [2, 3, 8])
test_mask = np.isin(y_test, [2, 3, 8])

X_train = X_train[train_mask]
y_train = y_train[train_mask]

X_test = X_test[test_mask]
y_test = y_test[test_mask]

# Remap labels: Bag=0, Dress=1, Pullover=2
label_map = {8: 0, 3: 1, 2: 2}

y_train = np.array([label_map[y] for y in y_train])
y_test = np.array([label_map[y] for y in y_test])

class_names = ['Bag', 'Dress', 'Pullover']

print("Training data:", X_train.shape)
print("Testing data:", X_test.shape)

# Step 5: Normalize, resize and convert to RGB
def preprocess_images(images):
    images = images.astype("float32")
    images = images.reshape(-1, 28, 28, 1)

    images = tf.image.resize(images, (32, 32))
    images = tf.image.grayscale_to_rgb(images)

    images = vgg16.preprocess_input(images)
    return images.numpy()

X_train = preprocess_images(X_train)
X_test = preprocess_images(X_test)

# One-hot encode the three classes
y_train = to_categorical(y_train, 3)
y_test = to_categorical(y_test, 3)

# Step 6: Load pre-trained VGG16 without its original head
vgg16_model = vgg16.VGG16(
    weights='imagenet',
    include_top=False,
    input_shape=(32, 32, 3)
)
vgg16_model.summary(show_trainable=True)

# Step 7: Create the classification model
def create_model(partial=False):

    # Load a fresh VGG16 model
    base_model = vgg16.VGG16(
        weights='imagenet',
        include_top=False,
        input_shape=(32, 32, 3)
    )

    # Freeze all convolutional layers initially
    base_model.trainable = False

    if partial:
        # Fine-tune only the last convolutional block
        base_model.trainable = True

        for layer in base_model.layers:
            layer.trainable = layer.name.startswith('block5')

    model = Sequential([
        Input(shape=(32, 32, 3)),
        base_model,
        GlobalAveragePooling2D(),
        Dense(128, activation='relu'),
        Dropout(0.5),
        Dense(3, activation='softmax')
    ])

    model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=0.0001),
        loss='categorical_crossentropy',
        metrics=['accuracy']
    )

    return model

# Step 8: Define callbacks
early_stopping = EarlyStopping(
    monitor='val_loss',
    patience=3,
    restore_best_weights=True
)

reduce_lr = ReduceLROnPlateau(
    monitor='val_loss',
    factor=0.5,
    patience=20,
    min_lr=1e-7
)

callbacks_list = [early_stopping, reduce_lr]

# Step 9: Train the FULL VGG16 model
full_model = create_model(partial=False)

full_model.summary(show_trainable=True)

history_full = full_model.fit(
    X_train,
    y_train,
    epochs=100,
    batch_size=32,
    validation_split=0.1,
    callbacks=callbacks_list
)

# Step 10: Train the PARTIALLY fine-tuned VGG16 model
partial_model = create_model(partial=True)

partial_model.summary(show_trainable=True)

history_partial = partial_model.fit(
    X_train,
    y_train,
    epochs=10,
    batch_size=32,
    validation_split=0.1,
    callbacks=[
        EarlyStopping(
            monitor='val_loss',
            patience=3,
            restore_best_weights=True
        ),
        ReduceLROnPlateau(
            monitor='val_loss',
            factor=0.5,
            patience=2,
            min_lr=1e-7
        )
    ]
)

# Step 11: Plot training and validation loss
plt.figure(figsize=(12, 5))

plt.subplot(1, 2, 1)
plt.plot(history_full.history['loss'], label='Training Loss')
plt.plot(history_full.history['val_loss'], label='Validation Loss')
plt.title('Full VGG16 Loss')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.legend()
plt.grid(True)

plt.subplot(1, 2, 2)
plt.plot(history_partial.history['loss'], label='Training Loss')
plt.plot(history_partial.history['val_loss'], label='Validation Loss')
plt.title('Partial VGG16 Loss')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.legend()
plt.grid(True)

plt.tight_layout()
plt.show()

# Step 12: Evaluate both models
full_loss, full_accuracy = full_model.evaluate(X_test, y_test)
partial_loss, partial_accuracy = partial_model.evaluate(X_test, y_test)

print("Full VGG16 Test Loss:", full_loss)
print("Full VGG16 Test Accuracy:", full_accuracy)

print("Partial VGG16 Test Loss:", partial_loss)
print("Partial VGG16 Test Accuracy:", partial_accuracy)

# Step 13: Predict test images
predictY = np.argmax(partial_model.predict(X_test[:10]), axis=1)
actualY = np.argmax(y_test[:10], axis=1)

for i in range(10):
    print("Actual:", class_names[actualY[i]],
          "| Predicted:", class_names[predictY[i]])

# Step 14: Recreate original test images and display predictions
# Load original dataset to extract the original grayscale test images
(_, _), (X_test_orig, _) = fashion_mnist.load_data()
test_images_original = X_test_orig[test_mask]

plt.figure(figsize=(12, 5))

for i in range(10):
    plt.subplot(2, 5, i + 1)

    # Display original test image
    plt.imshow(test_images_original[i], cmap='gray')
    plt.title(
        "True: " + class_names[actualY[i]] +
        "\nPred: " + class_names[predictY[i]]
    )
    plt.axis('off')

plt.tight_layout()
plt.show()