#Import necessary library here
import tensorflow as tf
from tensorflow.keras.datasets import mnist
from sklearn.model_selection import train_test_split
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Conv2D,MaxPooling2D,Flatten,Dense,Dropout
from tensorflow.keras.callbacks import EarlyStopping
import matplotlib.pyplot as plt
import numpy as np

#Load mnist datasets here
(X_train,y_train),(X_test,y_test)=mnist.load_data()

# showing shape of data
print(X_train.shape)
print(X_test.shape)

#Normalize data within range 0 and 1
X_train=X_train/255.0
X_test=X_test/255.0

#show training data
print(X_train)

#reshape data to add a channel dimension and use grayscale channel
X_train=X_train.reshape(-1,28,28,1)
X_test=X_test.reshape(-1,28,28,1)

#randomly split training datasets 90% for training and 10% for validation using train_test_split
X_train,X_val,y_train,y_val=train_test_split(X_train,y_train,test_size=0.10,stratify=y_train)

#build a sequential model
model=Sequential()

#build CNN model with two hidden layer of sizes 32,64 where strides=(1,1) maxpooling2D=(2,2)
#where activation is relu and softmax

model.add(Conv2D(32,kernel_size=(3,3),strides=(1,1),activation='relu',padding='same',input_shape=(28,28,1)))
model.add(MaxPooling2D(pool_size=(2,2)))
model.add(Dropout(0.25))
model.add(Conv2D(64,kernel_size=(3,3),strides=(1,1),activation='relu',padding='same'))
model.add(MaxPooling2D(pool_size=(2,2)))
model.add(Dropout(0.25))

#Flatten data or convert data into 1D array
model.add(Flatten())

#Design fully connected neural network
model.add(Dense(64,activation='relu'))
model.add(Dropout(0.5))
model.add(Dense(10,activation='softmax')) #output

#see model summary and total trainable parameters
model.summary()

#compile the model
model.compile(loss='sparse_categorical_crossentropy',optimizer='adam',metrics=['accuracy'])

#use earlystopping callbacks if validation loss does not decrease for 5 epochs
early_stopping=EarlyStopping(
    monitor='val_loss',
    patience=5,
    restore_best_weights=True
)

#Train the model
history=model.fit(X_train,y_train,epochs=100,validation_data=(X_val,y_val),callbacks=[early_stopping])

#plot the graph for training accuracy and validation accuracy
plt.plot(history.history['accuracy'], label="Training Accuracy")
plt.plot(history.history['val_accuracy'], label="Validation (Testing) Accuracy")
plt.xlabel("Epochs")
plt.ylabel("Accuracy")
plt.title("Training vs Testing Accuracy Graph")
plt.legend()

#plot the graph for training and validation loss
plt.plot(history.history['loss'], label="Training Loss")
plt.plot(history.history['val_loss'], label="Validation Loss")
plt.xlabel("Epochs")
plt.ylabel("Loss")
plt.title("Training and Validation Loss Graph")
plt.legend()

#Evaluate model on test sets
test_loss,test_accuracy=model.evaluate(X_test,y_test)
#print test loss and accuracy value
print(f"test loss: {test_loss:.5f}")
print(f"Test accuracy: {test_accuracy:.5f}")

#show actual test data
plt.imshow(X_test[101],cmap='gray')

#show answer predicted by machine
predictions=model.predict(X_test)
prediction_label=np.argmax(predictions,axis=1)

print(f"The machine predicted: {prediction_label[101]}")